import assert from 'node:assert/strict';
import {parseDailyRange,isOpenAt} from '../nowon/store_hours.mjs';
import {bloomColor,zoomLightStyle,shopGlowRadiusPx,SHOP_LIGHT_RADII_METERS} from '../nowon/light_canvas.mjs';
assert.deepEqual(parseDailyRange('19:00-03:00'),{start:1140,end:180});
assert.equal(parseDailyRange('00:00-00:00'),null);
assert.equal(parseDailyRange('25:00-03:00'),null);
assert.equal(isOpenAt({type:'daily',range:'19:00-03:00'},'23:59'),true);
assert.equal(isOpenAt({type:'daily',range:'19:00-03:00'},'02:59'),true);
assert.equal(isOpenAt({type:'daily',range:'19:00-03:00'},'03:01'),false);
assert.equal(isOpenAt({type:'daily',range:'08:00-20:00'},'21:00'),false);
assert.equal(isOpenAt({type:'247'},'02:00'),true);
assert.equal(isOpenAt(null,'02:00'),false);
assert.deepEqual(bloomColor('ngii_security'),[248,250,255]);
assert.deepEqual(bloomColor('ngii_street'),[255,217,142]);
assert.deepEqual(bloomColor('shop_light'),[159,214,255]);
assert.deepEqual(SHOP_LIGHT_RADII_METERS,[3,6,10,15]);
assert.ok(shopGlowRadiusPx(18,3)<shopGlowRadiusPx(18,10));
assert.ok(shopGlowRadiusPx(16,6)<shopGlowRadiusPx(18,6));
assert.ok(zoomLightStyle(12).core<zoomLightStyle(16).core);
console.log('store-hour manual preview and neutral light tones passed');
